/**
 * Package tags defines the documentation tags doxythings adds to Doxygen,
 * such as `@benchmark_run` and `@benchmarks`.
 *
 * Each Tag is the one definition of both its Doxygen alias (written out by
 * "doxythings init") and how it appears in Doxygen's XML (what package
 * doxygen collects), so the two can't drift apart.
 */
package tags

import (
	"fmt"
	"strings"
)

/**
 * Form is how a tag reaches Doxygen's XML.
 */
type Form int

const (
	/**
	 * Marker tags become an XML element visible only in the XML output:
	 * invisible in the HTML, they exist only for doxythings to read.
	 */
	Marker Form = iota
	/**
	 * XRefList tags become a `\xrefitem`: shown on the page as a labelled
	 * entry, listed on an index page, and with the argument resolved to an
	 * entity by Doxygen itself.
	 */
	XRefList
)

/**
 * Tag is one documentation tag taking a single argument.
 */
type Tag struct {
	/** Name is the command as written in comments, without the @. */
	Name string
	/** Usage describes the tag for the generated Doxyfile's comments. */
	Usage string
	/** Form is how the tag reaches the XML. */
	Form Form
	/** Key is the XML element name (Marker) or `\xrefitem` key (XRefList). */
	Key string
	/** Heading is the label shown beside each entry (XRefList only). */
	Heading string
	/**
	 * IndexTitle is the title of the index page listing every entry
	 * (XRefList only).
	 */
	IndexTitle string
}

/**
 * BenchmarkRun names the results that belong to a benchmark: the argument
 * exactly, or any "Name/..." (a parameterised benchmark's runs).
 */
var BenchmarkRun = Tag{
	Name:  "benchmark_run",
	Usage: `which results belong to this benchmark: Name exactly, or any "Name/..." (a parameterised benchmark's runs). Invisible in HTML.`,
	Form:  Marker,
	Key:   "doxythings-benchmark-run",
}

/**
 * Benchmarks names an entity a benchmark measures.
 */
var Benchmarks = Tag{
	Name:       "benchmarks",
	Usage:      `what this benchmark measures. Shown as a link, and listed on a "Benchmark Index" page.`,
	Form:       XRefList,
	Key:        "doxythings_benchmarks",
	Heading:    "Benchmarks",
	IndexTitle: "Benchmark Index",
}

/**
 * Alias returns the tag's Doxyfile ALIASES line.
 *
 * @return The ALIASES line.
 */
func (t Tag) Alias() string {
	var expansion string
	switch t.Form {
	case Marker:
		expansion = fmt.Sprintf(`\xmlonly<%s>\1</%s>\endxmlonly`, t.Key, t.Key)
	case XRefList:
		expansion = fmt.Sprintf(`\xrefitem %s \"%s\" \"%s\" \ref \1`, t.Key, t.Heading, t.IndexTitle)
	}
	return fmt.Sprintf(`ALIASES += %s{1}="%s"`, t.Name, expansion)
}

/**
 * Set is a group of tags, used together.
 */
type Set []Tag

/**
 * All is every tag doxythings defines.
 */
var All = Set{BenchmarkRun, Benchmarks}

/**
 * IsMarker reports whether name is the XML element of a Marker tag in the
 * set; it makes Set a doxygen.Vocabulary.
 *
 * @param name The XML element's name.
 * @return Whether a tag in the set uses it.
 */
func (s Set) IsMarker(name string) bool {
	for _, t := range s {
		if t.Form == Marker && t.Key == name {
			return true
		}
	}
	return false
}

/**
 * IsXRefKey reports whether key belongs to an XRefList tag in the set; it
 * makes Set a doxygen.Vocabulary.
 *
 * @param key The list's key.
 * @return Whether a tag in the set uses it.
 */
func (s Set) IsXRefKey(key string) bool {
	for _, t := range s {
		if t.Form == XRefList && t.Key == key {
			return true
		}
	}
	return false
}

/**
 * Doxyfile returns a Doxyfile fragment defining every tag in the set, meant
 * to be `@INCLUDE`d from a project's Doxyfile.
 *
 * @return The fragment.
 */
func (s Set) Doxyfile() string {
	var b strings.Builder
	b.WriteString("# doxythings' documentation tags. Generated by \"doxythings init\"; @INCLUDE\n")
	b.WriteString("# this from your Doxyfile.\n#\n")
	for _, t := range s {
		fmt.Fprintf(&b, "#   @%s{...}  %s\n", t.Name, t.Usage)
	}
	b.WriteString("#\n# Put these last in a comment block: \\xrefitem takes in the rest of its\n# paragraph.\n\n")
	for _, t := range s {
		b.WriteString(t.Alias() + "\n")
	}
	return b.String()
}
