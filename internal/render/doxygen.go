/**
 * Package render turns results and their links into output: Doxygen input
 * (a .dox file plus HTML fragments) or a standalone HTML page.
 *
 * It reads only package model and package link, never input formats or
 * Doxygen's XML, and a Markup decides how text and links are written for
 * each output, so all outputs share the same page builders.
 */
package render

import (
	"strconv"
	"strings"

	"github.com/nebulaeworks/doxythings/internal/link"
	"github.com/nebulaeworks/doxythings/internal/model"
)

/**
 * AnchorPrefix starts every anchor and fragment file name doxythings
 * generates, so stale fragments can be found and removed.
 */
const AnchorPrefix = "doxythings_"

/**
 * CSSClass is the class of the HTML elements styled by doxythings.css.
 */
const CSSClass = "doxythings"

/**
 * benchmarkAnchor is the anchor at a benchmark's Results section.
 *
 * @param b The benchmark.
 * @return The anchor's name.
 */
func benchmarkAnchor(b *link.Benchmark) string {
	return AnchorPrefix + b.Entity.RefID
}

/**
 * subjectAnchor is the anchor at a measured entity's Performance section.
 *
 * @param refID The entity's Doxygen id.
 * @return The anchor's name.
 */
func subjectAnchor(refID string) string {
	return AnchorPrefix + "subject_" + refID
}

/**
 * DoxygenOutput is everything one Doxygen render produces.
 */
type DoxygenOutput struct {
	/** Dox is the .dox file's content, to go on Doxygen's INPUT. */
	Dox string
	/**
	 * Fragments maps file names to HTML for `\htmlinclude`; their directory
	 * goes on Doxygen's EXAMPLE_PATH.
	 */
	Fragments map[string]string
	/** Problems lists anything that couldn't be shown where it belongs. */
	Problems []string
}

/**
 * DoxygenRenderer writes Doxygen input: an overview page, a Results section
 * on each benchmark, and a Performance section on each entity measured.
 */
type DoxygenRenderer struct {
	/** PageName is the overview page's `@page` name, used in links to it. */
	PageName string
	/** Title is the overview page's title. */
	Title string
	/** markup writes text and links for comments. */
	markup DoxygenMarkup
}

/**
 * Render produces Doxygen input. links is nil when there was no Doxygen
 * XML to link against: then only the overview page is made, without links.
 *
 * @param suites The results.
 * @param hostDetails Extra facts about the machine, shown with the host table.
 * @param links How results, benchmarks and entities connect, or nil.
 * @return The .dox content, the fragments and anything that couldn't be shown.
 */
func (r *DoxygenRenderer) Render(suites []*model.Suite, hostDetails model.Facts, links *link.Result) *DoxygenOutput {
	overview := &Overview{Suites: suites, HostDetails: hostDetails, Links: links}
	page := append([]string{"@page " + r.PageName + " " + r.Title, ""}, overview.Lines(r.markup)...)
	blocks := []string{commentBlock(page)}
	out := &DoxygenOutput{Fragments: map[string]string{}}

	var shown []*link.Benchmark
	for _, b := range links.Measured() {
		block, fragment, ok := r.benchmarkBlock(b, links)
		if !ok {
			out.Problems = append(out.Problems, b.Entity.Name+": can't attach results to a "+b.Entity.Kind)
			continue
		}
		blocks = append(blocks, block)
		out.Fragments[fragmentName(b)] = fragment
		shown = append(shown, b)
	}
	for _, s := range links.Subjects(shown) {
		block, ok := r.subjectBlock(s)
		if !ok {
			out.Problems = append(out.Problems,
				s.Entity.Name+": can't attach a Performance section to a "+s.Entity.Kind)
			continue
		}
		blocks = append(blocks, block)
	}

	out.Dox = "/* Generated by doxythings from benchmark results. Do not edit. */\n\n" +
		strings.Join(blocks, "\n")
	return out
}

/**
 * benchmarkBlock returns the comment block adding a Results section to b,
 * and the HTML fragment it includes; false if b's kind can't take one.
 *
 * @param b The benchmark.
 * @param links The matches, for b's results.
 * @return The comment block, the fragment's HTML, and whether b can take a
 * section.
 */
func (r *DoxygenRenderer) benchmarkBlock(b *link.Benchmark, links *link.Result) (string, string, bool) {
	command, ok := b.Entity.DocCommand()
	if !ok {
		return "", "", false
	}
	table := NewTable(append([]string{"Run", "n", "Iterations/rep"}, timeColumns...)...)
	for _, m := range links.Measurements(b) {
		row := []string{m.Run.Name, strconv.Itoa(m.Run.CPU().N), FormatCount(m.Run.Iterations)}
		table.AddTextRow(append(row, timeCells(m.Run)...)...)
	}
	fragment := strings.Join(table.Lines(HTMLMarkup{}), "\n") + "\n"
	block := commentBlock([]string{
		command, "",
		"@anchor " + benchmarkAnchor(b),
		"@par Results",
		"@htmlinclude " + fragmentName(b),
		r.allResultsNote(),
	})
	return block, fragment, true
}

/**
 * subjectBlock returns the comment block adding a collapsible Performance
 * section to a measured entity; false if its kind can't take one.
 *
 * @param s The measured entity, with its rows.
 * @return The comment block, and whether the entity can take a section.
 */
func (r *DoxygenRenderer) subjectBlock(s *link.Subject) (string, bool) {
	command, ok := s.Entity.DocCommand()
	if !ok {
		return "", false
	}
	table := NewTable("Benchmark", "CPU mean", "CPU median", "Real mean")
	for _, row := range s.Rows {
		run := row.Measurement.Run
		table.AddRow(
			Formatted(r.markup.Link(benchmarkAnchor(row.Benchmark), run.Name)),
			Text(FormatTime(run.CPU().Mean)), Text(FormatTime(run.CPU().Median)),
			Text(FormatTime(run.Real().Mean)))
	}
	body := append(table.Lines(r.markup), r.allResultsNote())
	lines := append([]string{command, "", "@anchor " + subjectAnchor(s.Entity.RefID)},
		collapsibleSection("Performance", body)...)
	return commentBlock(lines), true
}

/**
 * allResultsNote says where results come from, linking to the overview.
 *
 * @return The note, as Doxygen markup.
 */
func (r *DoxygenRenderer) allResultsNote() string {
	return `From the most recent benchmark run; see @ref ` + r.PageName + ` "all results".`
}

/**
 * fragmentName is the file name of b's Results fragment.
 *
 * @param b The benchmark.
 * @return The file name.
 */
func fragmentName(b *link.Benchmark) string {
	return benchmarkAnchor(b) + ".html"
}

/**
 * collapsibleSection wraps body in a section whose title, when clicked,
 * shows or hides the rest of it.
 *
 * @param title The section's title.
 * @param body The section's HTML lines.
 * @return The section's HTML lines.
 */
func collapsibleSection(title string, body []string) []string {
	lines := []string{`<details class="` + CSSClass + `">`, "<summary><b>" + title + "</b></summary>"}
	lines = append(lines, body...)
	return append(lines, "</details>")
}

/**
 * commentBlock wraps lines in a Doxygen block comment.
 *
 * @param lines The comment's lines.
 * @return The comment.
 */
func commentBlock(lines []string) string {
	var b strings.Builder
	b.WriteString("/**\n")
	for _, line := range lines {
		if line == "" {
			b.WriteString(" *\n")
		} else {
			b.WriteString(" * " + line + "\n")
		}
	}
	b.WriteString(" */\n")
	return b.String()
}
